import { describe, it, expect } from 'vitest';
import {
  publishAgUiEvent,
  getBufferedStreamEvents,
  clearInMemoryStreamChannel,
  recordJobRejectionMemory,
  recordStudioPhrasingMemory,
  GapResolutionItemSchema,
} from '@job-copilot/agents';
import { formatAgUiSseFrame } from '../../app/api/applications/[jobId]/stream/route';

describe('@job-copilot/web Surfaces, Resumable SSE Stream & Preference Memory Actions (Milestone 5)', () => {
  it('formats AG-UI SSE frames and replays missed sequence numbers on reconnect', async () => {
    const channelId = 'job-gen:linear-staff-ai';
    clearInMemoryStreamChannel(channelId);

    await publishAgUiEvent({
      packageId: 'pkg_1',
      streamChannelId: channelId,
      event: {
        type: 'STEP_STARTED',
        step: 'ANALYZING_REQUIREMENTS',
        message: 'Analyzing role blueprint',
        timestamp: new Date().toISOString(),
      },
    });

    await publishAgUiEvent({
      packageId: 'pkg_1',
      streamChannelId: channelId,
      event: {
        type: 'STEP_STARTED',
        step: 'SYNTHESIZING_RESUME',
        message: 'Synthesizing grounded resume bullets',
        timestamp: new Date().toISOString(),
      },
    });

    await publishAgUiEvent({
      packageId: 'pkg_1',
      streamChannelId: channelId,
      event: {
        type: 'TYPST_SOURCE_UPDATED',
        documentType: 'RESUME',
        typstSource: '// Generated by Job Copilot',
      },
    });

    const replayedFromSeq1 = await getBufferedStreamEvents(channelId, 1, {
      useDb: false,
    });

    expect(replayedFromSeq1).toHaveLength(2);
    expect(replayedFromSeq1.map((e) => e.seq)).toEqual([2, 3]);

    const sseText = formatAgUiSseFrame(replayedFromSeq1[0]!);
    expect(sseText).toContain('id: 2');
    expect(sseText).toContain('event: STEP_STARTED');
    expect(sseText).toContain('"step":"SYNTHESIZING_RESUME"');
  });

  it('distills job rejection and Studio phrasing edits into 768-dim Preference Memory and reinforces duplicate rules', async () => {
    const firstRejection = await recordJobRejectionMemory({
      profileId: 'prof_1',
      jobPostingId: 'job_1',
      companyName: 'MobileCorp',
      jobTitle: 'Senior React Native Developer',
      rejectionReasonCategory: 'Wrong Core Stack',
      userFeedbackNote: 'Skip roles focused on mobile React Native maintenance',
      existingRules: [],
    });

    expect(firstRejection.action).toBe('INSERTED');
    expect(firstRejection.confidenceWeight).toBe(1.0);
    expect(firstRejection.ruleStatement).toContain('React Native');

    const phrasingFirst = await recordStudioPhrasingMemory({
      profileId: 'prof_1',
      jobPostingId: 'job_1',
      originalTextSnippet: 'Spearheaded the development of a distributed task queue.',
      userEditedTextSnippet: 'Architected and scaled a distributed task queue.',
      defaultScope: 'RESUME_BULLETS',
      existingRules: [],
    });

    expect(phrasingFirst.action).toBe('INSERTED');
    expect(phrasingFirst.preferenceType).toBe('PHRASING_REPLACEMENT');
    expect(phrasingFirst.applicableScopes).toContain('RESUME_BULLETS');
  });

  it('validates inline GapResolutionCard payloads for ADDED_TO_PROFILE and BRIDGED paths', () => {
    const addEvidencePayload = GapResolutionItemSchema.parse({
      gapId: 'gap_k8s',
      action: 'ADDED_TO_PROFILE',
      newProfileEvidence: {
        experienceId: 'exp_1',
        skillName: 'Kubernetes',
        proficiency: 'PROFICIENT',
        newBulletText: 'Operated multi-cluster Kubernetes workloads serving 40k RPS.',
      },
    });

    expect(addEvidencePayload.action).toBe('ADDED_TO_PROFILE');
    expect(addEvidencePayload.newProfileEvidence?.skillName).toBe('Kubernetes');

    const bridgedPayload = GapResolutionItemSchema.parse({
      gapId: 'gap_cf_workers',
      action: 'BRIDGED',
      bridgeSkillName: 'AWS Lambda & Edge Functions',
      userGuidanceNote: 'Highlight edge runtime latency optimizations',
    });

    expect(bridgedPayload.action).toBe('BRIDGED');
    expect(bridgedPayload.bridgeSkillName).toBe('AWS Lambda & Edge Functions');
  });
});
