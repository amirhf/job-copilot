import type { TailoredResumePayload } from '@job-copilot/db';

export type TypstLayoutDensity = 'comfortable' | 'standard' | 'compact';

export interface CandidateHeaderInfo {
  fullName: string;
  email: string;
  phone?: string | null;
  locationCity: string;
  linkedinUrl?: string;
  githubUrl?: string;
  portfolioUrl?: string;
}

/**
 * Escapes special Typst markup characters (`#`, `$`, `*`, `_`, `@`, `<`, `>`, `\`, `[`, `]`)
 * so arbitrary technical strings (e.g. `C#`, `$2.4M`, `@mastra/core`) compile cleanly in Typst.
 */
export function escapeTypstText(raw: string): string {
  return raw
    .replace(/\\/g, '\\\\')
    .replace(/#/g, '\\#')
    .replace(/\$/g, '\\$')
    .replace(/\*/g, '\\*')
    .replace(/_/g, '\\_')
    .replace(/@/g, '\\@')
    .replace(/</g, '\\<')
    .replace(/>/g, '\\>')
    .replace(/\[/g, '\\[')
    .replace(/\]/g, '\\]');
}

export function renderResumeTypstSource(
  candidate: CandidateHeaderInfo,
  payload: TailoredResumePayload,
  density: TypstLayoutDensity = 'standard'
): string {
  const marginY =
    density === 'compact' ? '0.42in' : density === 'comfortable' ? '0.6in' : '0.5in';
  const marginX =
    density === 'compact' ? '0.48in' : density === 'comfortable' ? '0.6in' : '0.55in';
  const bodySize = density === 'compact' ? '9.2pt' : '9.6pt';
  const blockSpacing = density === 'compact' ? '5pt' : '7pt';

  const contactParts: string[] = [
    escapeTypstText(candidate.locationCity),
    escapeTypstText(candidate.email),
  ];
  if (candidate.phone) contactParts.push(escapeTypstText(candidate.phone));
  if (candidate.linkedinUrl) {
    contactParts.push(`#link("${candidate.linkedinUrl}")[LinkedIn]`);
  }
  if (candidate.githubUrl) {
    contactParts.push(`#link("${candidate.githubUrl}")[GitHub]`);
  }
  if (candidate.portfolioUrl) {
    contactParts.push(`#link("${candidate.portfolioUrl}")[Portfolio]`);
  }

  const lines: string[] = [
    `// Generated by @job-copilot/pdf-engine (density: ${density})`,
    `#set page(paper: "us-letter", margin: (x: ${marginX}, y: ${marginY}))`,
    `#set text(font: ("Inter", "Liberation Sans", "Helvetica"), size: ${bodySize}, fill: rgb("#111827"))`,
    `#set par(justify: false, leading: 0.52em)`,
    ``,
    `#align(center)[`,
    `  #text(size: 16pt, weight: "bold")[${escapeTypstText(candidate.fullName)}] \\`,
    `  #v(2pt)`,
    `  #text(size: 10pt, weight: "medium", fill: rgb("#374151"))[${escapeTypstText(payload.targetHeadline)}] \\`,
    `  #v(2pt)`,
    `  #text(size: 8.8pt, fill: rgb("#4B5563"))[${contactParts.join(' | ')}]`,
    `]`,
    `#v(${blockSpacing})`,
    `#line(length: 100%, stroke: 0.6pt + rgb("#D1D5DB"))`,
    ``,
  ];

  if (payload.executiveSummary.trim()) {
    lines.push(
      `#text(size: 10pt, weight: "bold", tracking: 0.04em)[SUMMARY]`,
      `#v(3pt)`,
      `${escapeTypstText(payload.executiveSummary)}`,
      `#v(${blockSpacing})`,
      ``
    );
  }

  if (payload.categorizedSkills.length > 0) {
    lines.push(
      `#text(size: 10pt, weight: "bold", tracking: 0.04em)[TECHNICAL SKILLS]`,
      `#v(3pt)`
    );
    for (const group of payload.categorizedSkills) {
      if (group.skills.length === 0) continue;
      lines.push(
        `*${escapeTypstText(group.categoryLabel)}:* ${escapeTypstText(group.skills.join(', '))} \\`
      );
    }
    lines.push(`#v(${blockSpacing})`, ``);
  }

  if (payload.selectedExperiences.length > 0) {
    lines.push(
      `#text(size: 10pt, weight: "bold", tracking: 0.04em)[EXPERIENCE]`,
      `#v(3pt)`
    );
    for (const exp of payload.selectedExperiences) {
      lines.push(
        `#grid(`,
        `  columns: (1fr, auto),`,
        `  [*${escapeTypstText(exp.jobTitle)}* — ${escapeTypstText(exp.companyName)} (${escapeTypstText(exp.locationText)})],`,
        `  [#text(style: "italic", fill: rgb("#4B5563"))[${escapeTypstText(exp.dateRangeText)}]]`,
        `)`,
        `#v(2pt)`
      );
      for (const b of exp.tailoredBullets) {
        lines.push(`- ${escapeTypstText(b.tailoredText)}`);
      }
      lines.push(`#v(${blockSpacing})`, ``);
    }
  }

  if (payload.selectedProjects.length > 0) {
    lines.push(
      `#text(size: 10pt, weight: "bold", tracking: 0.04em)[SELECTED PROJECTS]`,
      `#v(3pt)`
    );
    for (const proj of payload.selectedProjects) {
      lines.push(
        `*${escapeTypstText(proj.projectName)}* — ${escapeTypstText(proj.tailoredSummary)} \\`
      );
      for (const hl of proj.tailoredHighlights) {
        lines.push(`- ${escapeTypstText(hl)}`);
      }
      lines.push(`#v(${blockSpacing})`, ``);
    }
  }

  return lines.join('\n');
}

export function renderCoverLetterTypstSource(params: {
  candidate: CandidateHeaderInfo;
  companyName: string;
  jobTitle: string;
  coverLetterMarkdown: string;
}): string {
  const paragraphs = params.coverLetterMarkdown
    .split(/\n{2,}/)
    .map((p) => p.replace(/^#+\s*/gm, '').trim())
    .filter((p) => p.length > 0);

  const lines: string[] = [
    `// Generated Cover Letter by @job-copilot/pdf-engine`,
    `#set page(paper: "us-letter", margin: (x: 0.75in, y: 0.75in))`,
    `#set text(font: ("Inter", "Liberation Sans", "Helvetica"), size: 10.2pt, fill: rgb("#111827"))`,
    `#set par(justify: false, leading: 0.65em)`,
    ``,
    `#text(size: 15pt, weight: "bold")[${escapeTypstText(params.candidate.fullName)}] \\`,
    `#v(2pt)`,
    `#text(size: 9.2pt, fill: rgb("#4B5563"))[${escapeTypstText(params.candidate.locationCity)} | ${escapeTypstText(params.candidate.email)}]`,
    `#v(10pt)`,
    `#line(length: 100%, stroke: 0.6pt + rgb("#D1D5DB"))`,
    `#v(14pt)`,
    `*Re: ${escapeTypstText(params.jobTitle)} — ${escapeTypstText(params.companyName)}*`,
    `#v(10pt)`,
  ];

  for (const para of paragraphs) {
    lines.push(escapeTypstText(para), `#v(8pt)`);
  }

  return lines.join('\n');
}
